export function getUcMenuItem(id: string): UcMenuItem | undefined {
  return UC_MENU.find((i) => i.id === id);
}

export function ucItemsForPeriod(period: MealPeriod | null): UcMenuItem[] {
  if (!period) return [];
  return UC_MENU.filter((i) => i.timeZones.includes(period));
}

export function groupByCategory(items: UcMenuItem[]): Array<{
  category: string;
  items: UcMenuItem[];
}> {
  const map = new Map<string, UcMenuItem[]>();
  for (const item of items) {
    const list = map.get(item.category) ?? [];
    list.push(item);
    map.set(item.category, list);
  }
  return Array.from(map.entries()).map(([category, items]) => ({
    category,
    items,
  }));
}

export function formatHkd(amount: number): string {
  return `HK$${amount % 1 === 0 ? amount.toFixed(0) : amount.toFixed(1)}`;
}
